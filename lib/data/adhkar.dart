/// Adhkar from the authentic Sunnah, as commonly collected in Hisn al-Muslim.
/// Quranic passages are referenced by surah and verse and read from the
/// bundled Quran text, so their wording is exactly the mushaf's.
class Dhikr {
  const Dhikr({
    this.text,
    this.quran,
    required this.count,
    required this.source,
    this.note,
  });

  final String? text;

  /// (surah, first verse, last verse)
  final (int, int, int)? quran;
  final int count;
  final String source;
  final String? note;
}

class AdhkarCategory {
  const AdhkarCategory(this.id, this.title, this.items);

  final String id;
  final String title;
  final List<Dhikr> items;
}

